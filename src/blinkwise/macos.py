"""Install Blinkwise as a real macOS app: ~/Applications/Blinkwise.app.

A lightweight bundle around the Python environment Blinkwise is installed in
(for people who installed with pip/pipx). It is a menu-bar app (no Dock icon),
declares why it needs the camera (macOS terminates apps that open the camera
without NSCameraUsageDescription), and has a proper icon. For a fully
self-contained app with its own Python, see packaging/build_macos.sh.
"""

from __future__ import annotations

import os
import plistlib
import shlex
import sys
from pathlib import Path
from typing import Optional

from . import __version__

BUNDLE_ID = "com.blinkwise.app"
APP_NAME = "Blinkwise"
CAMERA_REASON = ("Blinkwise watches your blinking to remind you to rest your eyes. "
                 "Video is analysed on this Mac only and never stored or sent anywhere.")


def default_location() -> Path:
    return Path.home() / "Applications" / f"{APP_NAME}.app"


def info_plist(version: str = __version__) -> dict:
    return {
        "CFBundleName": APP_NAME,
        "CFBundleDisplayName": APP_NAME,
        "CFBundleIdentifier": BUNDLE_ID,
        "CFBundleVersion": version,
        "CFBundleShortVersionString": version,
        "CFBundlePackageType": "APPL",
        "CFBundleExecutable": APP_NAME,
        "CFBundleIconFile": APP_NAME,
        "LSUIElement": True,                    # menu-bar app: no Dock icon, no app menu
        "LSMinimumSystemVersion": "11.0",
        "NSHighResolutionCapable": True,
        "NSCameraUsageDescription": CAMERA_REASON,
        "LSApplicationCategoryType": "public.app-category.healthcare-fitness",
    }


def launcher_script(python: str) -> str:
    """The app's executable. Keeps Blinkwise running without anyone clicking anything:
    restarts it after a crash (backing off, giving up after 5 quick failures), switches
    to menu-bar-only mode if the watchdog asks (exit 75), and stops on Quit (exit 0) or
    when macOS logs out (SIGTERM)."""
    log = "$HOME/Library/Logs/Blinkwise.log"
    py = shlex.quote(python)
    return f"""#!/bin/bash
# Blinkwise launcher (generated by `blinkwise install-app`).
LOG="{log}"
mkdir -p "$HOME/Library/Logs"
# Keep the log small: start a fresh one when it passes 1 MB.
[ -f "$LOG" ] && [ "$(stat -f%z "$LOG" 2>/dev/null || echo 0)" -gt 1048576 ] && mv -f "$LOG" "$LOG.old"
trap 'kill -TERM "$child" 2>/dev/null; exit 0' TERM INT HUP
mode=()
fails=0
while true; do
  started=$(date +%s)
  {py} -m blinkwise run --app "${{mode[@]}}" "$@" >> "$LOG" 2>&1 &
  child=$!
  wait "$child"
  code=$?
  [ "$code" -eq 0 ] && exit 0                           # quit from the menu
  if [ "$code" -eq 75 ]; then mode=(--menubar-only); continue; fi
  if [ $(( $(date +%s) - started )) -lt 60 ]; then fails=$((fails + 1)); else fails=0; fi
  echo "$(date '+%Y-%m-%d %H:%M:%S') launcher: exited with code $code (quick failures: $fails)" >> "$LOG"
  [ "$fails" -ge 5 ] && exit 1
  sleep $(( fails * 5 + 2 ))
done
"""


def build_bundle(dest: Path, python: Optional[str] = None) -> Path:
    """Write the .app bundle at dest (works on any OS; only runs on macOS)."""
    python = python or sys.executable
    contents = dest / "Contents"
    (contents / "MacOS").mkdir(parents=True, exist_ok=True)
    (contents / "Resources").mkdir(parents=True, exist_ok=True)
    with open(contents / "Info.plist", "wb") as f:
        plistlib.dump(info_plist(), f)
    exe = contents / "MacOS" / APP_NAME
    exe.write_text(launcher_script(python))
    os.chmod(exe, 0o755)
    (contents / "PkgInfo").write_text("APPL????")
    write_icns(contents / "Resources" / f"{APP_NAME}.icns")
    return dest


def write_icns(path: Path) -> Path:
    from .ui.icon import app_icon
    img = app_icon(1024)
    img.save(path, format="ICNS", sizes=[(16, 16), (32, 32), (64, 64), (128, 128),
                                         (256, 256), (512, 512), (1024, 1024)])
    return path


def install(dest: Optional[Path] = None) -> Path:
    dest = dest or default_location()
    if dest.exists():
        uninstall(dest)
    build_bundle(dest)
    return dest


def uninstall(dest: Optional[Path] = None) -> bool:
    import shutil
    dest = dest or default_location()
    if not dest.exists():
        return False
    shutil.rmtree(dest)
    return True
